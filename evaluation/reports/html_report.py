    def generate(
        self,
        result: EvaluationResult,
        output_path: Path,
        visualizations: Optional[Dict[str, str]] = None,
        comparison_data: Optional[Dict] = None,
    ):
        """Generate the HTML report file."""
        visualizations = visualizations or {}
        m = result.metrics

        metric_cards = self._build_metric_cards(m)
        per_class_table = self._build_per_class_table(m.per_class_metrics)
        config_rows = self._build_config_rows(result.config or {})

        pr_path = visualizations.get("pr_curve", "pr_curves.png")
        cm_path = visualizations.get("confusion_matrix", "confusion_matrix.png")
        fp_path = visualizations.get("fp_gallery", "false_positives.png")
        fn_path = visualizations.get("fn_gallery", "false_negatives.png")

        regression_section = ""
        if comparison_data:
            regression_section = self._build_regression_section(comparison_data)

        html = self.TEMPLATE.format(
            title=f"Evaluation Report - {result.model_name} v{result.model_version}",
            model_name=result.model_name,
            model_version=result.model_version,
            dataset=result.dataset,
            timestamp=datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC"),
            metric_cards=metric_cards,
            per_class_table=per_class_table,
            pr_curve_path=pr_path,
            confusion_matrix_path=cm_path,
            fp_gallery_path=fp_path,
            fn_gallery_path=fn_path,
            config_rows=config_rows,
            regression_section=regression_section,
        )

        output_path.parent.mkdir(parents=True, exist_ok=True)
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(html)

    def _build_metric_cards(self, metrics) -> str:
        cards = [
            ("mAP50", metrics.mAP50, True),
            ("mAP50-95", metrics.mAP50_95, True),
            ("Precision", metrics.precision, True),
            ("Recall", metrics.recall, True),
            ("F1 Score", metrics.f1_score, True),
            ("FPS", metrics.fps, True),
            ("Latency (ms)", metrics.latency_ms, False),
            ("GPU Memory (MB)", metrics.gpu_memory_mb, False),
            ("Model Size (MB)", metrics.model_size_mb, False),
            ("Inference Cost", metrics.inference_cost_per_image, False),
        ]
        parts = []
        for label, value, higher_is_better in cards:
            css_class = "good" if higher_is_better else ""
            display = f"{value:.4f}" if value < 100 else f"{value:.1f}"
            parts.append(
                f'<div class="metric-card {css_class}">'
                f'<div class="value">{display}</div>'
                f'<div class="label">{label}</div></div>'
            )
        return "\n".join(parts)

    def _build_per_class_table(self, per_class: Dict) -> str:
        if not per_class:
            return "<p>No per-class metrics available.</p>"
        rows = ["<table><tr><th>Class</th><th>Precision</th><th>Recall</th>"
                "<th>F1</th><th>AP50</th><th>Support</th><th>TP</th><th>FP</th><th>FN</th></tr>"]
        for name, cm in sorted(per_class.items()):
            rows.append(
                f"<tr><td>{name}</td>"
                f"<td>{cm.precision:.4f}</td>"
                f"<td>{cm.recall:.4f}</td>"
                f"<td>{cm.f1_score:.4f}</td>"
                f"<td>{cm.ap50:.4f}</td>"
                f"<td>{cm.support}</td>"
                f"<td>{cm.tp}</td>"
                f"<td>{cm.fp}</td>"
                f"<td>{cm.fn}</td></tr>"
            )
        rows.append("</table>")
        return "\n".join(rows)

    def _build_config_rows(self, config: Dict) -> str:
        if not config:
            return "<tr><td colspan='2'>No configuration available</td></tr>"
        return "\n".join(
            f"<tr><td>{k}</td><td>{v}</td></tr>" for k, v in config.items()
        )

    def _build_regression_section(self, data: Dict) -> str:
        deltas = data.get("deltas", {})
        flags = data.get("flags", [])
        parts = ['<h2>Regression Analysis</h2>']
        if flags:
            parts.append('<div style="background:#ffeaa7; padding:1rem; border-radius:8px; margin:1rem 0;">')
            parts.append(f'<strong>Regressions detected:</strong> {", ".join(flags)}')
            parts.append('</div>')
        parts.append('<table><tr><th>Metric</th><th>Change</th></tr>')
        for k, v in deltas.items():
            cls = "status-fail" if k in flags else "status-pass"
            sign = "+" if v > 0 else ""
            parts.append(f'<tr><td>{k}</td><td class="{cls}">{sign}{v:.4f}</td></tr>')
        parts.append("</table>")
        return "\n".join(parts)
